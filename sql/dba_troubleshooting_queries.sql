-- 1. 锁等待关系与死锁阻塞源头深度排查
SELECT 
    W.ID AS 等待事务ID,
    W.WAIT_FOR_ID AS 阻塞源头事务ID,
    W.WAIT_TIME AS 等待耗时_ms,
    S1.SESS_ID AS 被阻塞会话ID,
    S1.SQL_TEXT AS 被阻塞SQL,
    S2.SESS_ID AS 源头会话ID_该杀,
    S2.USER_NAME AS 源头用户名,
    S2.CLNT_IP AS 源头客户端IP,
    S2.SQL_TEXT AS 源头SQL
FROM V$TRXWAIT W
LEFT JOIN V$SESSIONS S1 ON W.ID = S1.TRX_ID
LEFT JOIN V$SESSIONS S2 ON W.WAIT_FOR_ID = S2.TRX_ID;

