-- 3. 表空间综合容量与聚合使用率巡检
SELECT 
    TS.NAME AS 表空间名,
    COUNT(DF.PATH) AS 包含数据文件数,
    ROUND(SUM(DF.TOTAL_SIZE) * PAGE / 1024 / 1024.0, 2) AS 表空间总容量_MB,
    ROUND(SUM(DF.FREE_SIZE) * PAGE / 1024 / 1024.0, 2) AS 表空间剩余总空间_MB,
    ROUND((SUM(DF.TOTAL_SIZE) - SUM(DF.FREE_SIZE)) * PAGE / 1024 / 1024.0, 2) AS 已用总空间_MB,
    ROUND((SUM(DF.TOTAL_SIZE) - SUM(DF.FREE_SIZE)) * 100.0 / SUM(DF.TOTAL_SIZE), 2) AS "表空间综合使用率_%"
FROM V$TABLESPACE TS
JOIN V$DATAFILE DF ON TS.ID = DF.GROUP_ID
GROUP BY TS.NAME
ORDER BY "表空间综合使用率_%" DESC;

